export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem('mycloud_lang');
      if (saved === 'id' || saved === 'en') return saved;
      return 'id'; // default Bahasa Indonesia
    } catch (e) {
      return 'id';
    }
  });

  const setLang = (newLang) => {
    if (newLang !== 'id' && newLang !== 'en') return;
    setLangState(newLang);
    try {
      localStorage.setItem('mycloud_lang', newLang);
    } catch (e) {}
  };

  const t = (key, defaultText) => {
    if (translations[lang] && translations[lang][key] !== undefined) {
      return translations[lang][key];
    }
    return defaultText !== undefined ? defaultText : key;
  };

  // Translate with placeholder interpolation, e.g. tp('key', 'Hello {name}', { name })
  const tp = (key, defaultText, params = {}) => {
    let text = t(key, defaultText);
    Object.entries(params).forEach(([name, value]) => {
      text = text.split(`{${name}}`).join(String(value ?? ''));
    });
    return text;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, tp }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function localeFor(lang) {
  return lang === 'en' ? 'en-US' : 'id-ID';
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
